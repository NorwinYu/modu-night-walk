  // rounded box: keeps a box silhouette but softens every edge/corner
  function roundedBox(w, h, d, r = 0.12, seg = 3) {
    const g = new THREE.BoxGeometry(w, h, d, seg, seg, seg);
    const p = g.attributes.position; const v = new THREE.Vector3();
    const hw = Math.max(0.001, w / 2 - r), hh = Math.max(0.001, h / 2 - r), hd = Math.max(0.001, d / 2 - r);
    for (let i = 0; i < p.count; i++) {
      v.fromBufferAttribute(p, i);
      const cx = Math.max(-hw, Math.min(hw, v.x)), cy = Math.max(-hh, Math.min(hh, v.y)), cz = Math.max(-hd, Math.min(hd, v.z));
      const dx = v.x - cx, dy = v.y - cy, dz = v.z - cz;
      const l = Math.hypot(dx, dy, dz) || 1;
      v.set(cx + dx / l * r, cy + dy / l * r, cz + dz / l * r);
      p.setXYZ(i, v.x, v.y, v.z);
    }
    g.computeVertexNormals(); return g;
  }

